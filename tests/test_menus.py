"""The real menus: 3 businesses + 1 held-out, a realistic pizzeria, and the held-out guard."""

import pytest

from orderslm.menus import load_menu, load_menus, menu_version
from orderslm.paths import MENUS


def test_three_business_menus_and_one_held_out():
    business = load_menus()
    assert set(business) == {"corner-patty", "halfmoon-pizza", "morning-crumb"}
    assert not any(m.held_out for m in business.values())
    everything = load_menus(include_held_out=True)
    held = [b for b, m in everything.items() if m.held_out]
    assert held == ["lucky-lime"]


def test_held_out_menu_needs_explicit_opt_in():
    with pytest.raises(KeyError, match="include_held_out"):
        load_menu("lucky-lime")
    assert load_menu("lucky-lime", include_held_out=True).held_out


def test_held_out_menu_is_new_not_a_variant_of_a_business_menu():
    menus = load_menus(include_held_out=True)
    held = {i.id for i in menus["lucky-lime"].items}
    for b in ("corner-patty", "halfmoon-pizza", "morning-crumb"):
        assert not held & {i.id for i in menus[b].items}, b


def test_exactly_one_business_requires_a_name_for_pickup():
    assert [b for b, m in load_menus(include_held_out=True).items() if m.name_required_for_pickup] == [
        "morning-crumb"
    ]


def test_cafe_is_pickup_only():
    assert not load_menu("morning-crumb").delivery.available


def test_menu_version_is_a_stable_content_hash():
    m = load_menu("corner-patty")
    assert menu_version(m) == menu_version(load_menu("corner-patty"))
    changed = m.model_copy(update={"name": "Corner Patty 2"})
    assert menu_version(changed) != menu_version(m)
    assert menu_version(m).startswith("corner-patty@")


# ---- Halfmoon is a realistic pizzeria. The PIZZA benchmark catalog is separate: generated by the M2
# script into data/external/ (gitignored), never committed.


@pytest.fixture(scope="module")
def halfmoon():
    return load_menu("halfmoon-pizza")


def test_halfmoon_has_a_realistic_menu_size(halfmoon):
    groups = [m.group for m in halfmoon.modifiers]
    assert 15 <= groups.count("topping") <= 25
    assert 2 <= groups.count("crust") <= 5
    assert 5 <= sum(i.category == "pizzas" for i in halfmoon.items) <= 10
    assert 3 <= sum(i.category == "drinks" for i in halfmoon.items) <= 8


def test_every_pizza_allows_every_topping_sauce_and_crust(halfmoon):
    for p in (i for i in halfmoon.items if i.category == "pizzas"):
        assert p.allowed_modifier_ids == {m.id for m in halfmoon.modifiers}, p.id
        assert p.splittable, p.id


def test_pizza_size_must_be_stated_and_crust_is_exclusive(halfmoon):
    for p in (i for i in halfmoon.items if i.category == "pizzas"):
        assert {v.id for v in p.variants} == {"personal", "small", "medium", "large", "extra_large"}, p.id
        assert p.default_variant_id is None, p.id  # size must be stated or asked
    assert "crust" in halfmoon.exclusive_groups


def test_no_pizza_dataset_derived_file_is_committed():
    """PIZZA is CC-BY-NC-4.0: its benchmark catalog and coverage map live only in data/external/."""
    assert not list(MENUS.rglob("*pizza-coverage*"))
    assert not list(MENUS.rglob("*benchmark*"))
